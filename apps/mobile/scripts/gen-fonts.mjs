#!/usr/bin/env node
/**
 * The Coinbase fonts are licensed, so they are not in the public repo (assets/fonts/ and public/fonts/ are gitignored).
 * This script runs on postinstall, before prebuild and before each export:
 * - native: it writes src/lib/fonts.generated.ts with a static require() map of the TTFs in assets/fonts/.
 *   Without the files the map is empty, and the app uses the system font.
 * - web: it copies the woff2 files from assets/fonts/ to public/fonts/, so `expo export` puts them in dist/fonts/.
 *   public/index.html loads them with @font-face from /fonts/<name>.woff2.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = path.join(root, "assets", "fonts");
const publicDir = path.join(root, "public", "fonts");
const out = path.join(root, "src", "lib", "fonts.generated.ts");

/** The faces the theme uses (src/theme.ts). Only these are bundled. */
const FACES = [
  "CoinbaseSans-Regular", "CoinbaseSans-Medium", "CoinbaseSans-Bold",
  "CoinbaseDisplay-Medium", "CoinbaseDisplay-Bold",
  "CoinbaseMono-Regular", "CoinbaseMono-Medium",
];

const present = FACES.filter((f) => fs.existsSync(path.join(fontsDir, `${f}.ttf`)));
const lines = present.map((f) => `  "${f}": require("../../assets/fonts/${f}.ttf"),`);
const body = `// Generated by scripts/gen-fonts.mjs. Do not edit. ${present.length ? `${present.length} font files found.` : "No font files: the app uses the system font."}
/* eslint-disable @typescript-eslint/no-require-imports */
export const FONT_FILES: Record<string, number> = {
${lines.join("\n")}${lines.length ? "\n" : ""}};
`;
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);

let copied = 0;
for (const f of FACES) {
  const src = path.join(fontsDir, `${f}.woff2`);
  if (!fs.existsSync(src)) continue;
  fs.mkdirSync(publicDir, { recursive: true });
  const dst = path.join(publicDir, `${f}.woff2`);
  if (!fs.existsSync(dst) || fs.statSync(dst).size !== fs.statSync(src).size) fs.copyFileSync(src, dst);
  copied++;
}
console.log(`gen-fonts: ${present.length}/${FACES.length} TTF for native, ${copied}/${FACES.length} woff2 for web.`);
